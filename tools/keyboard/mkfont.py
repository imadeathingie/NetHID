def cols(art):
    rows = art.split()
    assert len(rows) == 7, (art, len(rows))
    out = []
    for c in range(5):
        byte = 0
        for r in range(7):
            assert len(rows[r]) == 5, rows[r]
            if rows[r][c] == '#':
                byte |= 1 << r
        out.append(byte)
    return out

def render(b):
    return "\n".join("".join('#' if (b[c] >> r) & 1 else '.' for c in range(5))
                     for r in range(7))

import sys
if '--check' in sys.argv:
    for ch in "ANH0359%":
        print("--", ch); print(render(cols(G[ch])))
    sys.exit(0)

lines = []
for i in range(0x20, 0x7F):
    ch = chr(i)
    src = G.get(ch)
    if src is None:
        up = ch.upper()
        src = G.get(up)                    # fold lowercase onto uppercase
    if src is None:
        src = G[' ']                       # unsupported: blank, not garbage
    b = cols(src)
    disp = ch if ch not in '\\"' else '\\' + ch
    lines.append("    { %s },  /* %s */" % (", ".join("0x%02X" % x for x in b), disp))
open('/tmp/font.txt','w').write("\n".join(lines))
print("%d glyphs, %d defined shapes" % (0x7F-0x20, len(G)))
